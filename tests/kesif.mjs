// v13.0 Keşfet sunucu testi: tutar okuma (Türkçe/İngilizce), yeni iş + geri alım listesi, tavan listesi, 30 dk ortak önbellek.
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const W = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'worker', 'src');
const db = new DatabaseSync(':memory:');
const mk = (sql, a = []) => { const o = { bind: (...x) => mk(sql, x), first: async () => db.prepare(sql).get(...a) ?? null, all: async () => ({ results: db.prepare(sql).all(...a) }), run: async () => db.prepare(sql).run(...a) }; return o; };
const env = { BT: { prepare: mk } };
db.exec('CREATE TABLE meta (k TEXT PRIMARY KEY, v TEXT)');
db.exec('CREATE TABLE kap (idx INTEGER PRIMARY KEY, t INTEGER, syms TEXT, title TEXT, subj TEXT, summ TEXT, tip TEXT, yon INTEGER, onem INTEGER, sent INTEGER DEFAULT 0)');
db.exec('CREATE INDEX kap_t ON kap(t)');
db.exec('CREATE TABLE kaph (idx INTEGER PRIMARY KEY, t INTEGER, d TEXT, sym TEXT, kind TEXT, subj TEXT, summ TEXT, txt TEXT, st INTEGER DEFAULT 0)');
db.exec('CREATE INDEX kaph_st ON kaph (st, kind, idx)');
const res = []; const ok = (n, c, i) => { res.push(!!c); console.log((c ? '✓ ' : '✗ ') + n + (i ? ' — ' + i : '')); };
const { kesAmount, kesNum, kesifData } = await import(path.join(W, 'kesif.js'));
const A = (t, v, c) => { const a = kesAmount(t); return v == null ? a == null : !!a && Math.abs(a.v - v) < 1 && a.c === c; };
ok('tutar: 111.719.627 TL', A('toplam 111.719.627 TL tutarında yeni sipariş', 111719627, 'TRY'));
ok('tutar: İngilizce TRY 111,719,627', A('total value of TRY 111,719,627.', 111719627, 'TRY'));
ok('tutar: 12.500.000 ABD Doları', A('bedeli 12.500.000 ABD Doları', 12.5e6, 'USD'));
ok('tutar: 3,2 milyon Avro', A('3,2 milyon Avro tutarında', 3.2e6, 'EUR'));
ok('tutar: USD 4.75 million (Türkçe büyük harf tuzağı)', A('worth USD 4.75 million', 4.75e6, 'USD'));
ok('tutar: 1.234.567,89 TL', A('KDV hariç 1.234.567,89 TL', 1234567.89, 'TRY'));
ok('tutar yoksa boş (yüzde, ton, tarih tutar sayılmaz)', A('300 ton üretim, pay %1,07, 19/10/2026', null));
ok('sayı çözme', kesNum('3,2') === 3.2 && kesNum('1.234,5') === 1234.5 && kesNum('111,719,627') === 111719627);
const now = Date.now(), D = 864e5;
const ins = (t, ...v) => db.prepare(t).run(...v);
ins('INSERT INTO kaph VALUES (?,?,?,?,?,?,?,?,?)', 100, now - 2 * D, '', 'CGCAM', 'is', 'Yeni İş İlişkisi', 'Sipariş Alınması', 'xx oda_ExplanationTextBlock| toplam 111.719.627 TL tutarında sipariş', 1);
ins('INSERT INTO kaph VALUES (?,?,?,?,?,?,?,?,?)', 90, now - 40 * D, '', 'ESKI', 'is', 'Yeni İş İlişkisi', 'eski', 'oda_ExplanationTextBlock| 5.000.000 TL', 1);
ins('INSERT INTO kaph VALUES (?,?,?,?,?,?,?,?,?)', 95, now - 3 * D, '', 'BEKLE', 'is', 'Yeni İş İlişkisi', 'detay yok', '', 0);
ins('INSERT INTO kap (idx,t,syms,summ,tip,onem) VALUES (?,?,?,?,?,?)', 100, now - 2 * D, 'CGCAM', 'Sipariş Alınması', 'is', 3);
ins('INSERT INTO kap (idx,t,syms,summ,tip,onem) VALUES (?,?,?,?,?,?)', 110, now - 3600e3, 'ASELS,ASLSN', 'Yeni sözleşme', 'is', 3);
[1, 2, 3].forEach(k => ins('INSERT INTO kap (idx,t,syms,summ,tip,onem) VALUES (?,?,?,?,?,?)', 200 + k, now - k * D, 'SASA', 'Geri alım', 'geri', 2));
ins('INSERT INTO kap (idx,t,syms,summ,tip,onem) VALUES (?,?,?,?,?,?)', 210, now - D / 2, 'THYAO', 'Geri alım', 'geri', 2);
ins('INSERT INTO kap (idx,t,syms,summ,tip,onem) VALUES (?,?,?,?,?,?)', 220, now - 9 * D, 'ESKIG', 'Geri alım', 'geri', 2);
ins("INSERT INTO meta VALUES ('tavan_list', ?)", JSON.stringify({ d: '2026-10-19', L: [{ s: 'MCARD', c: 97.35 }] }));
ins('INSERT INTO kap (idx,t,syms,summ,tip,onem) VALUES (?,?,?,?,?,?)', 300, now - 10 * D, 'EREGL', 'Bedelsiz sermaye artırımı SPK başvurusu', 'bedelsiz', 3);
ins('INSERT INTO kap (idx,t,syms,summ,tip,onem) VALUES (?,?,?,?,?,?)', 301, now - 40 * D, 'ESKSA', 'eski bedelli', 'bedelli', 3);
const r = await kesifData(env);
const cg = r.is.find(x => x.sym === 'CGCAM');
ok('yeni iş: detaylı haberde tutar var, aynı haber iki kez yok', cg && cg.amt === 111719627 && cg.cur === 'TRY' && r.is.filter(x => x.idx === 100).length === 1, JSON.stringify(r.is));
ok('yeni iş: bugünkü (detayı henüz toplanmamış) haber de listede, tutarsız', r.is.some(x => x.sym === 'ASELS' && x.amt == null) && r.is[0].sym === 'ASELS');
ok('yeni iş: 30 günden eski ve detayı bekleyen yok', !r.is.some(x => x.sym === 'ESKI' || x.sym === 'BEKLE'));
ok('geri alım: 7 gün, hisse başına sayım, çoktan aza', r.geri.length === 2 && r.geri[0].sym === 'SASA' && r.geri[0].n === 3 && r.geri[1].sym === 'THYAO', JSON.stringify(r.geri));
ok('dün tavan kapananlar', r.tavan && r.tavan.L[0].s === 'MCARD');
ok('sermaye artırımı: son 30 gün, eskisi yok', r.sa.length === 1 && r.sa[0].sym === 'EREGL' && r.sa[0].tip === 'bedelsiz', JSON.stringify(r.sa));
ins('INSERT INTO kap (idx,t,syms,summ,tip,onem) VALUES (?,?,?,?,?,?)', 230, now - 600e3, 'KONTR', 'Geri alım', 'geri', 2);
const r2 = await kesifData(env);
ok('30 dk ortak önbellek: yeni satır hemen görünmez', r2.at === r.at && !r2.geri.some(x => x.sym === 'KONTR'));
const r3 = await kesifData(env, true);
ok('zorla yeniden hesap yeni satırı görür', r3.geri.some(x => x.sym === 'KONTR'));
console.log('\nKeşfet: ' + res.filter(Boolean).length + '/' + res.length);
process.exit(res.every(Boolean) ? 0 : 1);
